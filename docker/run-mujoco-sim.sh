#!/bin/bash
# Run the overall-sim container with everything the sim needs:
#   GPU (Vulkan/EGL/GLX) + X11 (viewer window) + /dev/input (keyboard) +
#   host network (DDS domain shared with the tinynav container / navcore).
#
# Default form is hil: DDS contract topics + viser web viewer :8012 +
# keyboard teleop (arrows override /cmd_vel). sim = the no-DDS sandbox.
#
# Usage: bash docker/run-mujoco-sim.sh [hil|sim|mj|dog] [extra entrypoint args]
#       e.g. bash docker/run-mujoco-sim.sh sim --web-port 8014
#       MJSIM_DDS_IFACE=<wire nic> bash docker/run-mujoco-sim.sh dog -- --profile go2
#       (the dog form gets the viser viewer on 8012 by default)
set -u
FORM="${1:-hil}"; shift || true
NAME="mjsim-${FORM}"

# Repo bind mounts: sim/ (scene+emu code) and assets/floorplan/ (parametric
# scene config) come from the host tree, so edits land on container restart
# instead of needing docker cp -- which a container RECREATE silently
# reverts to the baked copy.  MJSIM_BIND_REPO=0 falls back to the baked
# image tree; MJSIM_IMAGE picks the image (default mjsim:jazzy).
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIND_ARGS=()
if [ "${MJSIM_BIND_REPO:-1}" != 0 ]; then
  for sub in mujoco/sim mujoco/assets/floorplan; do
    [ -d "$ROOT/$sub" ] && BIND_ARGS+=(-v "$ROOT/$sub:/workspace/tinynav-sim/$sub")
  done
  # entrypoints too: the qpos side-channel for offboard video capture lives
  # in dog.py, and docker cp'd edits vanish on container recreate
  for f in mujoco/dog.py mujoco/hil.py; do
    [ -f "$ROOT/$f" ] && BIND_ARGS+=(-v "$ROOT/$f:/workspace/tinynav-sim/$f")
  done
fi
MJSIM_IMAGE="${MJSIM_IMAGE:-mjsim:jazzy}"

# DDS: the image bakes a loopback-unicast CYCLONEDDS_URI (the single-host
# recipe, proven against VPN-TUN route hijacking). Cross-machine peers -- the
# pilot rig over the wire -- need the domain pinned to the wire NIC instead:
# MJSIM_DDS_IFACE=<NIC> overrides with a generated config. Multicast stays on,
# so the pinned link finds the remote peer AND same-host listeners alike.
DDS_ARGS=()
if [ -n "${MJSIM_DDS_IFACE:-}" ]; then
  DDS_CFG="/tmp/mjsim_cdds_${MJSIM_DDS_IFACE}.xml"
  cat > "$DDS_CFG" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by run-mujoco-sim.sh: MJSIM_DDS_IFACE=${MJSIM_DDS_IFACE} -->
<CycloneDDS xmlns="https://cdds.io/config">
  <Domain Id="any">
    <General>
      <Interfaces>
        <NetworkInterface name="${MJSIM_DDS_IFACE}"/>
      </Interfaces>
    </General>
  </Domain>
</CycloneDDS>
EOF
  DDS_ARGS+=(-v "$DDS_CFG:/opt/dds/cdds_iface.xml:ro" -e CYCLONEDDS_URI=file:///opt/dds/cdds_iface.xml)
  echo "dds: pinned to ${MJSIM_DDS_IFACE} (overriding the baked loopback config)"
fi

# dog.py itself defaults headless (--view none) for bench/CI callers; from
# this script the viewer is wanted every time, so default it on at the hil
# form's port. An explicit --view / --web-port wins.
if [ "$FORM" = dog ]; then
  case "$*" in *--view*)     : ;; *) set -- "$@" --view web ;; esac
  case "$*" in *--web-port*) : ;; *) set -- "$@" --web-port 8012 ;; esac
fi

docker rm -f "$NAME" >/dev/null 2>&1 || true

# keyboard capture needs the input group's gid from the host
#
# /dev/input is bind-mounted live WITH a device-cgroup rule for the whole
# input major (13) rather than passed as `--device /dev/input`: --device
# snapshots the nodes present at container creation, so a keyboard that
# appears later (re-plugged, re-paired, or simply a different event number)
# stays invisible until the container is restarted -- which reads as
# "the keyboard stopped working" while nothing in the sim changed.
INPUT_GID="$(getent group input | cut -d: -f3)"

docker run -d --name "$NAME" \
  --gpus all \
  -e NVIDIA_DRIVER_CAPABILITIES=graphics,compute,utility \
  -e DISPLAY="${DISPLAY:-:1}" \
  -v /tmp/.X11-unix:/tmp/.X11-unix \
  ${XDG_RUNTIME_DIR:+-v "$XDG_RUNTIME_DIR:$XDG_RUNTIME_DIR" -e XDG_RUNTIME_DIR} \
  -v /dev/input:/dev/input \
  --device-cgroup-rule "c 13:* rwm" \
  ${INPUT_GID:+--group-add "$INPUT_GID"} \
  $(for d in /dev/dri/card0 /dev/dri/card1 /dev/dri/renderD128 /dev/dri/renderD129; do [ -e "$d" ] && echo -n "--device $d "; done) \
  --network host \
  --ipc host \
  -e MUJOCO_GL=egl \
  ${DDS_ARGS[@]+"${DDS_ARGS[@]}"} \
  ${BIND_ARGS[@]+"${BIND_ARGS[@]}"} \
  "$MJSIM_IMAGE" "$FORM" "$@"

echo "container '$NAME' up (form=$FORM)"
echo "  logs:   docker logs -f $NAME"
echo "  web:    http://127.0.0.1:8012/   (viser viewer; --web-port N moves it)"
echo "  stream: http://127.0.0.1:8888/   (--preview only)"
echo "  topics: /camera/camera/infra1|infra2|depth|color|vio_*|imu  (DDS)"
echo "  stop:   docker rm -f $NAME"
